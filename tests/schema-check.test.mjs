import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { readFileSync, mkdtempSync, writeFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { Address, StrKey, xdr } from "@stellar/stellar-sdk";
import { validateReport } from "../tools/schema-check/index.mjs";

const contract = Address.fromString(StrKey.encodeContract(Buffer.alloc(32,7))).toScAddress();
function invocation(method, children = []) {
  return new xdr.SorobanAuthorizedInvocation({
    function:xdr.SorobanAuthorizedFunction.sorobanAuthorizedFunctionTypeContractFn(
      new xdr.InvokeContractArgs({contractAddress:contract,functionName:method,args:[]})), subInvocations:children
  });
}
const encoded = children => new xdr.SorobanAuthorizationEntry({
  credentials:xdr.SorobanCredentials.sorobanCredentialsSourceAccount(),
  rootInvocation:invocation("withdraw", children)
}).toXdr("base64");
function fixture(t, content) {
  const dir=mkdtempSync(join(tmpdir(),"authscope-schema-"));
  t.after(()=>rmSync(dir,{recursive:true,force:true}));
  const path=join(dir,"report.json");writeFileSync(path,typeof content === "string" ? content : JSON.stringify(content));
  return path;
}
function run(script,...args) {
  return spawnSync(process.execPath,[resolve(script),...args],{encoding:"utf8",timeout:12000,env:{...process.env,NODE_OPTIONS:""}});
}
test("schemas declare strict Draft 2020-12 with recursive invocation", () => {
  for(const name of ["snapshot","comparison"]) {
    const schema=JSON.parse(readFileSync(resolve(`schemas/v1/${name}.schema.json`),"utf8"));
    assert.equal(schema.$schema,"https://json-schema.org/draft/2020-12/schema");
    assert.equal(schema.additionalProperties,false);
    assert.equal(schema.properties.schemaVersion.const,1);
  }
});
test("documented v1 fixtures have the expected validity", () => {
  for(const name of ["valid-snapshot-v1","valid-comparison-v1","invalid-missing-credential",
    "invalid-unknown-kind","invalid-negative-count"]) {
    const fixture=JSON.parse(readFileSync(resolve(`schemas/fixtures/${name}.json`),"utf8"));
    assert.equal(validateReport(fixture).valid,name.startsWith("valid-"),name);
  }
});
test("validator accepts real outputs generated by existing CLI",t => {
  const before=fixture(t,{auth:[encoded([])]});
  const after=fixture(t,{auth:[encoded([invocation("transfer")])]});
  const snapshot=run("dist/cli.js","inspect",after,"--json");
  assert.equal(snapshot.status,0,snapshot.stderr);
  const a=JSON.parse(snapshot.stdout);
  assert.equal(validateReport(a).valid,true);
  const diff=run("dist/cli.js","diff",before,after,"--json");
  assert.equal(diff.status,1,diff.stderr);
  const b=JSON.parse(diff.stdout);
  assert.equal(validateReport(b).valid,true);
  const file=fixture(t,b);
  assert.equal(run("tools/schema-check/index.mjs",file,"--type","comparison").status,0);
});
test("malformed credentials, versions, trees and unknown delta kinds are rejected", () => {
  const valid= {schemaVersion:1,authorizationCount:1,entries:[{
    credential:"sorobanCredentialsSourceAccount",authorizer:"transaction source",delegates:[],root:{
      kind:"contract",contract:"Cexample",method:"approve",argumentsSha256:"a".repeat(64),children:[]}}]};
  assert.equal(validateReport(valid).valid,true);
  const candidates=[
    {...valid,schemaVersion:2},
    {...valid,entries:[{...valid.entries[0],credential:undefined}]},
    {...valid,entries:[{...valid.entries[0],root:{...valid.entries[0].root,children:[{}]}}]},
    {...valid,entries:[{...valid.entries[0],delegateTree:[{address:"GDELEGATE",children:[{}]}]}]},
    {...valid,authorizationCount:2},
    {...valid,authorizationCount:-1},
    {...valid,unexpected:1},
    {schemaVersion:1,changed:true,beforeCount:0,afterCount:1,changes:[{kind:"changed",authorizer:"x",path:"y",count:1}]},
    {schemaVersion:1,changed:true,beforeCount:0,afterCount:1,changes:[{kind:"added",authorizer:"x",path:"y",count:-1}]}
  ];
  for(const value of candidates) assert.equal(validateReport(value).valid,false,JSON.stringify(value));
});
test("excessive nesting, size and JSON errors exit with bounded diagnostics",t => {
  let node={kind:"contract",contract:"C",method:"f",argumentsSha256:"0".repeat(64),children:[]};
  for(let i=0;i<26;i++) node={...node,children:[node]};
  assert.equal(validateReport({schemaVersion:1,authorizationCount:1,entries:[{
    credential:"sorobanCredentialsSourceAccount",authorizer:"transaction source",delegates:[],root:node}]}).valid,false);
  const oversized=fixture(t," ".repeat(4*1024*1024+1));
  const err=run("tools/schema-check/index.mjs",oversized);
  assert.equal(err.status,2);
  assert.ok(err.stderr.length<500);
  const invalid=fixture(t,"{bad");
  assert.equal(run("tools/schema-check/index.mjs",invalid).status,2);
});
